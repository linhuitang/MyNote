const messages: Record<AppLocale, TranslationTable> = { en, 'zh-CN': zhCN }

export function useI18n() {
  const locale = useState<AppLocale>('app-locale', () => 'en')
  const intlLocale = computed(() => locale.value === 'zh-CN' ? 'zh-CN' : 'en-US')

  function t(key: TranslationKey, parameters: Record<string, string | number> = {}): string {
    return Object.entries(parameters).reduce(
      (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
      messages[locale.value][key],
    )
  }

  function setLocale(value: AppLocale): void {
    locale.value = value
    if (import.meta.client) localStorage.setItem(STORAGE_KEY, value)
  }

  function initialiseLocale(): void {
    if (!import.meta.client) return
    const savedLocale = localStorage.getItem(STORAGE_KEY)
    if (savedLocale === 'en' || savedLocale === 'zh-CN') locale.value = savedLocale
  }

  return { locale, locales: appLocaleOptions, intlLocale, t, setLocale, initialiseLocale }
}
